#!/usr/bin/env bash
# PROD-COMPAT-01 device matrix (GATE.md row 10, the headline GA gate). Drives fb-gate.sh across a curated
# device list that spans the audit axes — GPU vendor {Adreno, Mali new+old, (Xclipse/PowerVR where the
# catalog allows)} × OS {api 31..35} × form-factor {phone, cutout-landscape, foldable, tablet} — and
# aggregates each device's per-mode VERDICT into MATRIX-RESULTS.md. Each row IS the per-device gating record
# the audit calls for; TV is scoped out for v1 (COMPAT-03 — Test Lab has no physical TV GPU).
#
# Cost: each run is one Firebase Test Lab PHYSICAL device-minute slice. Spark plan = 5 physical runs/day free;
# beyond that needs Blaze billing (~$5/device-hour). Default modes recon+rlhd = ~2 runs/device. Use --modes
# and the device tiers to stay inside whatever budget the operator approved.
#
# Usage:
#   ./fb-matrix.sh --tier core            # ~6 devices (the representative gate) × default modes
#   ./fb-matrix.sh --tier full            # the full curated list (foldable/tablet/old-OS too)
#   ./fb-matrix.sh --devices "shiba:34:phone:mali, dm1q:34:phone:adreno"   # explicit list
#   ./fb-matrix.sh --modes recon          # caps-tier readout only (cheapest per-device gate)
#   ./fb-matrix.sh --modes recon,rlhd,gpu # full per-device renderer proof
#   ./fb-matrix.sh --tier core --dry-run  # print the plan + run count, spend nothing
#
# A device entry is  model:version:formfactor:vendor[:orientation]  (orientation default portrait; use
# landscape for the cutout axis). model/version must be valid Test Lab ids (gcloud firebase test android
# models list / versions list).
set -euo pipefail

HERE="$(cd "$(dirname "$0")" && pwd)"
GATE="$HERE/fb-gate.sh"
OUT="$HERE/MATRIX-RESULTS.md"

MODES="recon,rlhd"
TIER=""
DEVICES_ARG=""
DRY=0
while [ $# -gt 0 ]; do
	case "$1" in
		--tier)     TIER="$2"; shift 2 ;;
		--modes)    MODES="$2"; shift 2 ;;
		--devices)  DEVICES_ARG="$2"; shift 2 ;;
		--dry-run)  DRY=1; shift ;;
		-h|--help)  sed -n '2,24p' "${BASH_SOURCE[0]}" | sed 's/^# \{0,1\}//'; exit 0 ;;
		*) echo "fb-matrix: unknown arg '$1' (see --help)" >&2; exit 64 ;;
	esac
done

# Curated device lists. model ids verified against `gcloud firebase test android models list` (2026-06-24).
# vendor is the BEST-EFFORT GPU family (Test Lab does not expose silicon; flagged where region-ambiguous) —
# the recon VERDICT reports the ACTUAL GL_RENDERER per device, which is the ground truth that supersedes this.
CORE_DEVICES=(
	"shiba:34:phone:mali-g715"          # Pixel 8 — Mali new (Tensor G3); the Pixel-7a baseline's sibling
	"bluejay:32:phone:mali-g78"         # Pixel 6a — Mali OLD (Android 12 / api 32)
	"dm1q:34:phone:adreno-740"          # Galaxy S23 — Adreno (Snapdragon 8 Gen 2)
	"husky:35:phone:mali-g715"          # Pixel 8 Pro — Mali new on api 35 (newest OS)
	"XQ-DQ72:34:landscape:adreno-cutout"  # Sony Xperia 1 V — Adreno + the cutout-landscape axis
	"akita:34:phone:mali-g715"          # Pixel 8a — Mali new, mid-tier thermal envelope
)
EXTRA_DEVICES=(
	"comet:35:foldable:mali-g715"       # Pixel 9 Pro Fold — foldable, large square panel
	"b5q:34:foldable:adreno"            # Galaxy Z Flip5 — foldable Adreno
	"gta8wifi:34:tablet:mali-mid"       # Galaxy Tab A8 — tablet (lower-tier GPU)
	"e3q:34:phone:adreno-750"           # Galaxy S24 Ultra — Adreno newest (Snapdragon 8 Gen 3)
)

declare -a DEVICES
if [ -n "$DEVICES_ARG" ]; then
	IFS=',' read -ra raw <<< "$DEVICES_ARG"
	for d in "${raw[@]}"; do d="$(echo "$d" | xargs)"; [ -n "$d" ] && DEVICES+=("$d"); done
elif [ "$TIER" = "full" ]; then
	DEVICES=("${CORE_DEVICES[@]}" "${EXTRA_DEVICES[@]}")
else
	DEVICES=("${CORE_DEVICES[@]}")   # default + --tier core
fi

IFS=',' read -ra MODE_LIST <<< "$MODES"
total=$(( ${#DEVICES[@]} * ${#MODE_LIST[@]} ))
echo "== device matrix: ${#DEVICES[@]} device(s) × ${#MODE_LIST[@]} mode(s) ($MODES) = $total Test Lab run(s) =="
for d in "${DEVICES[@]}"; do echo "   - $d"; done
if [ "$DRY" -eq 1 ]; then echo "(dry-run — no runs dispatched)"; exit 0; fi

ts="$(date '+%Y-%m-%d %H:%M' 2>/dev/null || echo 'run')"
{
	echo "# PROD-COMPAT-01 device-matrix results"
	echo
	echo "> Generated by fb-matrix.sh on $ts. Modes: \`$MODES\`. Each cell is the fb-gate.sh VERDICT on that"
	echo "> device's fetched logcat. \`recon\` = GLES caps tier + base-gpu shader compile; \`rlhd\` = 117HD Zone"
	echo "> shaders compile + startUp on the real driver; \`gpu\` = base gpu plugin renders. PASS/NOT_GREEN/SKIP."
	echo
	echo "| Device | API | Form | GPU (label) | $(printf '%s | ' "${MODE_LIST[@]}")"
	echo "|--------|-----|------|-------------|$(for _ in "${MODE_LIST[@]}"; do printf -- '------|'; done)"
} > "$OUT"

for entry in "${DEVICES[@]}"; do
	IFS=':' read -r model version form vendor orient <<< "$entry"
	orient="${orient:-portrait}"
	[ "$form" = "landscape" ] && orient="landscape"
	row="| $model | $version | $form | $vendor |"
	echo
	echo "════════════════════════════════════════════════════════════════════"
	echo "▶ $model (api $version, $form, $vendor, orientation=$orient)"
	echo "════════════════════════════════════════════════════════════════════"
	for mode in "${MODE_LIST[@]}"; do
		echo "── $model :: $mode ──"
		set +e
		FB_DEVICE="$model" FB_VERSION="$version" FB_ORIENTATION="$orient" \
			"$GATE" "$mode" 2>&1 | tee "/tmp/fbm-$model-$mode.log"
		rc=${PIPESTATUS[0]}
		set -e
		verdict="$(grep -oE 'VERDICT=[A-Za-z0-9_]+' "/tmp/fbm-$model-$mode.log" | tail -1 | sed 's/VERDICT=//')"
		[ -z "$verdict" ] && verdict="$([ "$rc" -eq 0 ] && echo PASS || echo NOT_GREEN)"
		row="$row $verdict |"
	done
	echo "$row" >> "$OUT"
	echo "   -> $row"
done

echo
echo "════════════════════════════════════════════════════════════════════"
echo "✅ matrix complete — results table: $OUT"
echo "════════════════════════════════════════════════════════════════════"
cat "$OUT"
